#!/bin/bash
# gen_syscall_table.sh — Generate lib/Nacre/SyscallTable.pm from kernel headers.
#
# The table maps every syscall name to its number on x86_64 and aarch64, for
# the names in seccomp profiles. It is generated here so that nacre needs no
# kernel headers on the machine it runs on.
#
# Usage:
#   scripts/gen_syscall_table.sh            # x86_64 and aarch64
#   scripts/gen_syscall_table.sh --check    # verify SyscallTable.pm matches (for CI)
#
# Requirements:
#   - cc, and the kernel headers (linux-libc-dev on Debian and Ubuntu)
#   - for aarch64: gcc-aarch64-linux-gnu (only its preprocessor is run);
#     without it the aarch64 table already in SyscallTable.pm is kept

set -euo pipefail
cd "$(dirname "$0")/.."

OUT=lib/Nacre/SyscallTable.pm
TMPDIR=$(mktemp -d)
trap 'rm -rf "$TMPDIR"' EXIT

mode=generate
for arg in "$@"; do
    case "$arg" in
        --check) mode=check ;;
    esac
done

# Print "name number" for every __NR_<name> the compiler's asm/unistd.h
# defines. The preprocessor resolves what the headers leave to it, such as the
# aliases of __NR3264_* numbers and the names only 32-bit builds get on
# aarch64. __NR_syscalls and __NR_arch_specific_syscall are not syscalls.
syscalls() {
    local cc=$1 names
    names=$("$cc" -E -dM -include asm/unistd.h -x c /dev/null |
        sed -n 's/^#define __NR_\([a-z0-9_]*\) .*/\1/p' |
        grep -vxE 'syscalls|arch_specific_syscall' | sort -u)
    for name in $names; do
        echo "@@ $name __NR_$name"
    done | "$cc" -E -P -include asm/unistd.h -x c - | sed -n 's/^@@ //p' > "$TMPDIR/out"
    if grep -vqE '^[a-z0-9_]+ [0-9]+$' "$TMPDIR/out"; then
        echo "$cc: a syscall number is not a plain number:" >&2
        grep -vE '^[a-z0-9_]+ [0-9]+$' "$TMPDIR/out" >&2
        exit 1
    fi
    cat "$TMPDIR/out"
}

# The lines of the heredoc <tag> in the current SyscallTable.pm
existing() {
    sed -n "/^    $1 => <<'$1',\$/,/^$1\$/p" "$OUT" | sed '1d;$d'
}

echo "Reading the x86_64 headers..." >&2
syscalls cc > "$TMPDIR/x86_64.txt"

if command -v aarch64-linux-gnu-gcc > /dev/null; then
    echo "Reading the aarch64 headers..." >&2
    syscalls aarch64-linux-gnu-gcc > "$TMPDIR/aarch64.txt"
else
    echo "aarch64-linux-gnu-gcc not found: keeping the aarch64 table in $OUT." >&2
    existing AARCH64 > "$TMPDIR/aarch64.txt"
    [ -s "$TMPDIR/aarch64.txt" ] || { echo "no aarch64 table in $OUT" >&2; exit 1; }
fi

gen() {
cat <<'HEADER'
package Nacre::SyscallTable;
use v5.38;

# ═══════════════════════════════════════════════════════════════════════
# THIS FILE IS GENERATED by scripts/gen_syscall_table.sh — do not edit manually.
# ═══════════════════════════════════════════════════════════════════════
#
# Syscall name -> number on each architecture nacre runs on, for the names in
# seccomp profiles. Only the table asked for is split into a hash; the other
# is never more than a string.

my %TABLE = (
HEADER
echo "    X86_64 => <<'X86_64',"
cat "$TMPDIR/x86_64.txt"
echo "X86_64"
echo "    AARCH64 => <<'AARCH64',"
cat "$TMPDIR/aarch64.txt"
echo "AARCH64"
cat <<'FOOTER'
);

# The table for this machine's architecture, as name => number; empty on an
# architecture nacre has no table for.
sub native_table () {
    require Config;
    my $arch = $Config::Config{archname} // '';    ## no critic (ProhibitPackageVars)
    return table('X86_64') if $arch =~ /x86_64|amd64/i;
    return table('AARCH64') if $arch =~ /aarch64|arm64/i;
    return;
}

# The table for X86_64 or AARCH64 (for the tests)
sub table ($key) {
    return split ' ', $TABLE{$key} // '';
}

1;
FOOTER
}

generated=$(gen)

if [ "$mode" = check ]; then
    if diff -u "$OUT" <(echo "$generated") >&2; then
        echo "OK: $OUT is up to date." >&2
    else
        echo "FAIL: $OUT is out of date. Run: scripts/gen_syscall_table.sh" >&2
        exit 1
    fi
else
    echo "$generated" > "$OUT"
    perl -c "$OUT" 2>&1
    echo "Generated $OUT" >&2
fi
